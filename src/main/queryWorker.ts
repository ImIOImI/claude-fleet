// Off-main-thread runner for the MCP `query` tool (#476).
//
// The query tool builds a per-call in-memory snapshot of the caller's
// allowed-workspace rows (#146) and runs the caller's SQL against it. On a
// multi-GB state.db that copy takes minutes, and it used to run synchronously
// on the Electron main thread — freezing the whole app (UI IPC, terminals,
// every other MCP call) for the duration. It now runs in a worker thread with
// a hard timeout: the caller gets a clear error, the main loop never blocks.
//
// The worker is an `eval` worker (same pattern as perfSentinel.ts) so no extra
// bundle entry is needed. Its body is runSnapshotQuery serialized via
// toString(), so runSnapshotQuery MUST stay self-contained: it may use only its
// parameters — no imports, no module-level constants, no helpers.
//
// better-sqlite3 is required in the worker by absolute path. In packaged builds
// main resolves it inside app.asar; the whole better-sqlite3 tree is
// asarUnpacked (electron-builder.yml) and has no dependencies, so we point the
// worker at the app.asar.unpacked copy — a plain on-disk path that needs no
// asar support inside the worker.
//
// better-sqlite3 has no interrupt API, so terminate() cannot stop a worker that
// is inside a single long native SQLite statement: the thread finishes that
// statement, then exits. The caller is released at the timeout regardless;
// such still-running workers are counted as "zombies" and new queries are
// refused while too many are alive, so runaway SQL can't pile up CPU/memory.

import { Worker } from 'node:worker_threads';
import { createRequire } from 'node:module';
import { existsSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import type BetterSqlite3 from 'better-sqlite3';
import { MAX_QUERY_BYTES, SNAPSHOT_EVENT_COLS } from './store/readSource.js';

export const QUERY_TIMEOUT_MS = 30_000;
/** Concurrently running query workers; further calls queue (queue time counts toward the timeout). */
export const MAX_CONCURRENT_QUERIES = 2;
/** Timed-out workers still finishing a native statement; at this many, new queries are refused. */
export const MAX_ZOMBIE_QUERIES = 2;

export interface SnapshotQueryJob {
  /** Path of the live state.db to ATTACH (never ':memory:'). */
  srcPath: string;
  /** Allowed workspace ids — the snapshot contains only these rows. */
  allowed: string[];
  includeRaw: boolean;
  sql: string;
  params: unknown[];
  maxRows: number;
  maxBytes: number;
  /** `events` columns copied into the snapshot (raw_jsonl appended only when includeRaw). */
  eventCols: string;
  /** Random ATTACH alias (generated by the caller: the worker body can't import crypto helpers). */
  alias: string;
}

/** Build a throwaway in-memory DB containing ONLY the allowed-workspace rows,
 *  DETACH the source, then run the caller's SQL against it. Isolation is
 *  structural: the source is detached before the caller's SQL runs, so no
 *  subquery/UNION/sqlite_master trick can reach unfiltered rows (#146).
 *  SELF-CONTAINED — serialized into the worker via toString(). */
export function runSnapshotQuery(
  DatabaseCtor: typeof BetterSqlite3, job: SnapshotQueryJob, zlib: { inflateSync(b: Uint8Array): Buffer },
): unknown[] {
  const ids = job.allowed;
  // Empty set matches nothing (self is always present, so unreachable in practice).
  const scope = ids.length === 0 ? '0 = 1' : `workspace_id IN (${ids.map(() => '?').join(',')})`;
  const alias = job.alias;
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(alias)) throw new Error('invalid snapshot alias');

  const mem = new DatabaseCtor(':memory:');
  try {
    // Retention stores old lines deflated in raw_z with raw_jsonl ''.
    mem.function('fleet_raw', { deterministic: true }, (raw: unknown, z: unknown) => {
      if (!(z instanceof Uint8Array) || z.length === 0) return raw;
      try {
        return zlib.inflateSync(z).toString('utf8');
      } catch {
        return raw;
      }
    });
    // ATTACH filename is not reliably bindable; double any single quotes.
    mem.exec(`ATTACH DATABASE '${job.srcPath.replace(/'/g, "''")}' AS ${alias}`);
    try {
      if (job.includeRaw) {
        // A view inflates only the rows a query reads; the snapshot keeps the compressed bytes.
        const srcCols = mem.prepare(`PRAGMA ${alias}.table_info(events)`).all() as { name: string }[];
        const rawZ = srcCols.some((c) => c.name === 'raw_z') ? 'raw_z' : 'NULL AS raw_z';
        mem.prepare(`CREATE TABLE events_store AS SELECT ${job.eventCols}, raw_jsonl, ${rawZ} FROM ${alias}.events WHERE ${scope}`).run(...ids);
        mem.exec(`CREATE VIEW events AS SELECT ${job.eventCols}, fleet_raw(raw_jsonl, raw_z) AS raw_jsonl FROM events_store`);
      } else {
        mem.prepare(`CREATE TABLE events AS SELECT ${job.eventCols} FROM ${alias}.events WHERE ${scope}`).run(...ids);
      }
      for (const t of ['sessions', 'broker_sessions', 'session_summaries', 'session_tags', 'usage_events']) {
        mem.prepare(`CREATE TABLE ${t} AS SELECT * FROM ${alias}.${t} WHERE ${scope}`).run(...ids);
      }
      // perf_events: app-global rows (workspace_id NULL — stalls, slow ops)
      // are host-process facts visible to every caller; workspace-tagged rows
      // are scoped like everything else.
      try {
        mem.prepare(
          `CREATE TABLE perf_events AS SELECT * FROM ${alias}.perf_events WHERE workspace_id IS NULL OR ${scope}`
        ).run(...ids);
      } catch (e) {
        // Pre-v11 DB (no perf_events yet): an empty, correctly-shaped table.
        // Anything else is a real failure and must surface.
        if (!(e instanceof Error && /no such table/i.test(e.message))) throw e;
        mem.exec(`CREATE TABLE perf_events (id INTEGER PRIMARY KEY AUTOINCREMENT, ts INTEGER NOT NULL, kind TEXT NOT NULL, workspace_id TEXT, session_id TEXT, name TEXT, dur_ms REAL, trace_id TEXT, span_id TEXT, meta TEXT)`);
      }
      try {
        mem.prepare(`CREATE TABLE port_exposures AS SELECT * FROM ${alias}.port_exposures WHERE ${scope}`).run(...ids);
      } catch (e) {
        // Pre-v15 DB: an empty, correctly-shaped table instead of an error.
        if (!(e instanceof Error && /no such table/i.test(e.message))) throw e;
        mem.exec(
          `CREATE TABLE port_exposures (id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL, session_id TEXT, ` +
            `port INTEGER NOT NULL, cmdline TEXT, label TEXT, reason TEXT, source TEXT NOT NULL, ` +
            `first_scanned_at INTEGER, declared_at INTEGER, popup_shown_at INTEGER, outcome TEXT, ` +
            `opened_via TEXT, open_count INTEGER NOT NULL DEFAULT 0, ended_at INTEGER)`
        );
      }
    } finally {
      mem.exec(`DETACH ${alias}`);
    }

    const stmt = mem.prepare(job.sql);
    if (!stmt.reader) throw new Error('read-only SELECT statements only');
    const rows = (stmt.all(...job.params) as unknown[]).slice(0, job.maxRows);
    const bytes = JSON.stringify(rows).length;
    if (bytes > job.maxBytes) {
      throw new Error(`result too large (${bytes} bytes > ${job.maxBytes}); add LIMIT or aggregate server-side`);
    }
    return rows;
  } finally {
    mem.close();
  }
}

const WORKER_SRC = `
const { parentPort, workerData } = require('node:worker_threads');
const run = (${runSnapshotQuery.toString()});
try {
  const Database = require(workerData.bs3Path);
  parentPort.postMessage({ ok: true, rows: run(Database, workerData.job, require('node:zlib')) });
} catch (e) {
  parentPort.postMessage({ ok: false, message: e && e.message ? e.message : String(e) });
}
`;

/** Absolute path the worker can require better-sqlite3 from (asar-unpacked in packaged builds). */
export function betterSqlitePath(): string {
  const p = createRequire(import.meta.url).resolve('better-sqlite3');
  const unpacked = p.replace(/app\.asar([\\/])/, 'app.asar.unpacked$1');
  return unpacked !== p && existsSync(unpacked) ? unpacked : p;
}

let running = 0;
let zombies = 0;
const waiters: Array<() => void> = [];

/** Live counts, for tests and diagnostics. */
export function queryWorkerStats(): { running: number; zombies: number; queued: number } {
  return { running, zombies, queued: waiters.length };
}

export interface RunQueryOptions {
  timeoutMs?: number;
  /** Test seam: replaces the worker body (e.g. one that never answers). */
  workerSource?: string;
}

/** Run a snapshot query in a worker thread. Rejects with a clear error on
 *  timeout (the worker is terminated) or on any SQL/snapshot failure. Never
 *  blocks the calling thread beyond spawning the worker. */
export async function runQueryInWorker(
  job: Omit<SnapshotQueryJob, 'alias' | 'maxBytes' | 'eventCols'> & { maxBytes?: number },
  opts: RunQueryOptions = {}
): Promise<unknown[]> {
  const timeoutMs = opts.timeoutMs ?? QUERY_TIMEOUT_MS;
  const deadline = Date.now() + timeoutMs;
  const timedOut = () => new Error(`query timed out after ${Math.round(timeoutMs / 1000)}s — narrow the query`);

  if (zombies >= MAX_ZOMBIE_QUERIES) {
    throw new Error(
      `query refused: ${zombies} earlier timed-out queries are still finishing on the host — retry shortly with a narrower query`
    );
  }

  // Concurrency gate (each worker may copy a large snapshot into memory).
  if (running >= MAX_CONCURRENT_QUERIES) {
    await new Promise<void>((resolve, reject) => {
      const t = setTimeout(() => {
        const i = waiters.indexOf(go);
        if (i >= 0) waiters.splice(i, 1);
        reject(timedOut());
      }, Math.max(0, deadline - Date.now()));
      const go = () => {
        clearTimeout(t);
        resolve();
      };
      waiters.push(go);
    });
  }
  running += 1;

  const fullJob: SnapshotQueryJob = {
    ...job,
    maxBytes: job.maxBytes ?? MAX_QUERY_BYTES,
    eventCols: SNAPSHOT_EVENT_COLS,
    alias: 'src_' + randomBytes(6).toString('hex')
  };

  let released = false;
  const release = () => {
    if (released) return;
    released = true;
    running -= 1;
    waiters.shift()?.();
  };

  try {
    return await new Promise<unknown[]>((resolve, reject) => {
      let settled = false;
      let abandoned = false;
      const worker = new Worker(opts.workerSource ?? WORKER_SRC, {
        eval: true,
        workerData: { bs3Path: betterSqlitePath(), job: fullJob }
      });
      const settle = (fn: () => void) => {
        if (settled) return;
        settled = true;
        clearTimeout(timer);
        fn();
      };
      const timer = setTimeout(() => {
        settle(() => {
          // Release the caller now. If the worker is inside a native SQLite
          // statement it exits only when that returns — count it until then.
          abandoned = true;
          zombies += 1;
          void worker.terminate();
          reject(timedOut());
        });
      }, Math.max(0, deadline - Date.now()));
      worker.once('message', (m: { ok: boolean; rows?: unknown[]; message?: string }) => {
        settle(() => (m.ok ? resolve(m.rows ?? []) : reject(new Error(m.message ?? 'query failed'))));
      });
      worker.once('error', (e) => settle(() => reject(e)));
      worker.once('exit', (code) => {
        if (abandoned) zombies -= 1;
        settle(() => reject(new Error(`query worker exited unexpectedly (code ${code})`)));
      });
    });
  } finally {
    release();
  }
}
