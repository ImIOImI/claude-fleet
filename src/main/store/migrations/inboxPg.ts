// Postgres DDL for inbox.db: the baseline is the schema at version 5; each
// later version is a step, so a store migrated at 5 picks it up in place.
// Byte-order text, as SQLite compares it: sort order must not follow the server locale.
import type { PgMigrationStep, PgTrack } from '../pgMigrate.js';

const T = 'TEXT COLLATE "C"';

export const INBOX_PG_BASELINE_VERSION = 5;

export const INBOX_PG_BASELINE = `
CREATE TABLE todos (
  id ${T} PRIMARY KEY,
  title ${T} NOT NULL,
  body ${T},
  status ${T} NOT NULL CHECK (status IN ('open','done','dismissed')),
  priority ${T} NOT NULL CHECK (priority IN ('low','normal','high','urgent')),
  source_kind ${T} NOT NULL CHECK (source_kind IN ('user','workspace','automation')),
  source_id ${T},
  source_run_id ${T},
  via_workspace ${T},
  dedupe_key ${T},
  seen_count BIGINT NOT NULL DEFAULT 1,
  recurred BIGINT NOT NULL DEFAULT 0,
  workspace_id ${T},
  session_id ${T},
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  first_seen_at BIGINT NOT NULL,
  last_seen_at BIGINT NOT NULL,
  closed_at BIGINT
);
CREATE UNIQUE INDEX todos_dedupe ON todos (source_kind, COALESCE(source_id, ''), dedupe_key)
  WHERE dedupe_key IS NOT NULL;
CREATE INDEX todos_open ON todos (status, priority, last_seen_at);
CREATE TABLE tags (
  entity_kind ${T} NOT NULL,
  entity_id ${T} NOT NULL,
  tag ${T} NOT NULL,
  PRIMARY KEY (entity_kind, entity_id, tag)
);
CREATE TABLE todo_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  todo_id ${T} NOT NULL,
  ts BIGINT NOT NULL,
  kind ${T} NOT NULL,
  actor_kind ${T} NOT NULL,
  actor_id ${T},
  run_id ${T},
  detail ${T}
);
CREATE INDEX todo_events_todo ON todo_events (todo_id, id);

CREATE TABLE notifications (
  id ${T} PRIMARY KEY,
  ts BIGINT NOT NULL,
  kind ${T} NOT NULL,
  title ${T} NOT NULL,
  body ${T},
  priority ${T} NOT NULL,
  source_kind ${T} NOT NULL,
  source_id ${T},
  todo_id ${T},
  workspace_id ${T},
  dedupe_key ${T},
  tags ${T},
  delivered BIGINT NOT NULL,
  held_reason ${T},
  channel ${T},
  cleared_at BIGINT,
  digested BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX notifications_ts ON notifications (ts);
CREATE TABLE notification_rules (
  id ${T} PRIMARY KEY,
  scope_kind ${T} NOT NULL CHECK (scope_kind IN ('key','source','tag','global')),
  scope_value ${T} NOT NULL,
  level ${T} NOT NULL CHECK (level IN ('all','high','urgent','off')),
  snooze_until BIGINT,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  UNIQUE (scope_kind, scope_value)
);
CREATE TABLE downtimes (
  id ${T} PRIMARY KEY,
  name ${T} NOT NULL,
  enabled BIGINT NOT NULL,
  days_mask BIGINT NOT NULL,
  start_min BIGINT NOT NULL,
  end_min BIGINT NOT NULL,
  bypass ${T} NOT NULL CHECK (bypass IN ('none','urgent','urgent+input')),
  created_at BIGINT NOT NULL
);
CREATE TABLE notify_state (k ${T} PRIMARY KEY, v ${T} NOT NULL);

CREATE TABLE automations (
  id ${T} PRIMARY KEY,
  name ${T} NOT NULL UNIQUE,
  enabled BIGINT NOT NULL,
  version BIGINT NOT NULL,
  definition ${T} NOT NULL,
  created_by_kind ${T} NOT NULL,
  created_by_id ${T},
  origin ${T},
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  last_scheduled_at BIGINT,
  next_run_at BIGINT,
  next_run_by ${T}
);
CREATE TABLE automation_versions (
  automation_id ${T} NOT NULL,
  version BIGINT NOT NULL,
  definition ${T} NOT NULL,
  created_at BIGINT NOT NULL,
  created_by_kind ${T} NOT NULL,
  created_by_id ${T},
  PRIMARY KEY (automation_id, version)
);
CREATE TABLE automation_state (automation_id ${T} PRIMARY KEY, state ${T} NOT NULL);
CREATE TABLE runs (
  id ${T} PRIMARY KEY,
  automation_id ${T} NOT NULL,
  version BIGINT NOT NULL,
  trigger ${T} NOT NULL,
  args ${T} NOT NULL,
  status ${T} NOT NULL,
  started_at BIGINT NOT NULL,
  ended_at BIGINT,
  error ${T},
  reschedule ${T}
);
CREATE INDEX runs_automation ON runs (automation_id, started_at);
CREATE INDEX runs_status ON runs (status);
CREATE TABLE step_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id ${T} NOT NULL,
  step_id ${T} NOT NULL,
  kind ${T} NOT NULL,
  status ${T} NOT NULL,
  workspace_id ${T},
  broker_session_id ${T},
  started_at BIGINT NOT NULL,
  ended_at BIGINT,
  error ${T},
  detail ${T}
);
CREATE INDEX step_runs_run ON step_runs (run_id, id);

CREATE TABLE proposals (
  id ${T} PRIMARY KEY,
  kind ${T} NOT NULL CHECK (kind IN ('new','change','batch')),
  proposer_kind ${T} NOT NULL,
  proposer_id ${T},
  rationale ${T},
  status ${T} NOT NULL,
  items ${T} NOT NULL,
  note ${T},
  created_at BIGINT NOT NULL,
  decided_at BIGINT
);
CREATE INDEX proposals_status ON proposals (status, created_at);
`;

// Steps after the baseline mirror inbox.db MIGRATIONS 6+ (inbox/inboxDb.ts).
// Expand-only (pgMigrate.ts): new tables, added columns, a widened CHECK.
export const INBOX_PG_STEPS: readonly PgMigrationStep[] = [
  // #483: knowledge claims (phase 1) + background capture runs. claims_fts is
  // SQLite's FTS5 index; here a plain side table with the same columns, which
  // ClaimStore.ftsIds searches with to_tsvector/to_tsquery.
  {
    version: 6,
    postgres: `
CREATE TABLE claims (
  id ${T} PRIMARY KEY,
  text ${T} NOT NULL,
  kind ${T} NOT NULL,
  topics ${T} NOT NULL,
  refs ${T},
  visibility ${T} NOT NULL DEFAULT 'fleet',
  status ${T} NOT NULL DEFAULT 'current',
  superseded_by ${T},
  retract_reason ${T},
  workspace_id ${T} NOT NULL,
  confirmations BIGINT NOT NULL DEFAULT 1,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);
CREATE INDEX idx_claims_status_vis ON claims (status, visibility, workspace_id);
CREATE TABLE claim_sources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  claim_id ${T} NOT NULL,
  workspace_id ${T} NOT NULL,
  session_id ${T},
  via ${T} NOT NULL,
  capture_run ${T},
  ts BIGINT NOT NULL
);
CREATE INDEX idx_claim_sources_claim ON claim_sources (claim_id);
CREATE TABLE claim_vectors (claim_id ${T} PRIMARY KEY, model_id ${T} NOT NULL, vec BYTEA NOT NULL);
CREATE TABLE claims_fts (claim_id ${T}, text ${T}, topics ${T});
CREATE TABLE capture_runs (
  id ${T} PRIMARY KEY,
  workspace_id ${T} NOT NULL,
  session_id ${T} NOT NULL,
  fork_session_id ${T},
  trigger ${T} NOT NULL,
  status ${T} NOT NULL,
  claims_recorded BIGINT NOT NULL DEFAULT 0,
  usage ${T},
  error ${T},
  started_at BIGINT NOT NULL,
  ended_at BIGINT
);
CREATE INDEX idx_capture_runs_session ON capture_runs (session_id, started_at);
CREATE INDEX idx_capture_runs_status ON capture_runs (status);
`
  },
  // #483 §5a: capture-settings change log, proposals kind 'capture-settings'
  // + payload, and the capture_runs user-turn baseline.
  {
    version: 7,
    postgres: `
CREATE TABLE capture_settings_log (
  id ${T} PRIMARY KEY,
  workspace_id ${T} NOT NULL,
  ts BIGINT NOT NULL,
  actor ${T} NOT NULL,
  "before" ${T} NOT NULL,
  "after" ${T} NOT NULL,
  reason ${T},
  applied BIGINT NOT NULL,
  proposal_id ${T}
);
CREATE INDEX idx_capture_settings_log_ws ON capture_settings_log (workspace_id, ts);
ALTER TABLE proposals DROP CONSTRAINT proposals_kind_check;
ALTER TABLE proposals ADD CONSTRAINT proposals_kind_check CHECK (kind IN ('new','change','batch','capture-settings'));
ALTER TABLE proposals ADD COLUMN payload ${T};
ALTER TABLE capture_runs ADD COLUMN user_turns BIGINT;
CREATE INDEX idx_capture_runs_started ON capture_runs (started_at);
`
  },
  // #483 final review: capture_runs visibility + compaction count at admit.
  {
    version: 8,
    postgres: `
ALTER TABLE capture_runs ADD COLUMN visibility ${T};
ALTER TABLE capture_runs ADD COLUMN compactions BIGINT;
`
  }
];

export const INBOX_PG_TRACK: PgTrack = { track: 'inbox', baselineVersion: INBOX_PG_BASELINE_VERSION, baseline: INBOX_PG_BASELINE, steps: INBOX_PG_STEPS };
